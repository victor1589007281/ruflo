package builtin

import (
	"sort"

	"github.com/anthropic/claude-go/pkg/tool"
)

// ToolNameCatalog 返回某个档位下**内置**工具的名字全集 (已排序)。
//
// ---------------------------------------------------------------------------
// 存在的理由: 一份写错工具名的黑名单, 在运行期是完全隐形的
// ---------------------------------------------------------------------------
//
// `disallowed-tools: [bash]` (小写) 与 `disallowed-tools: [Bash]` 在装配读数上
// 一模一样 —— 都会被接上, 都会出现在生效黑名单里, 都不会有任何报错。区别只在
// 运行期: 前者一个工具都挡不住 (注册表里叫 `Bash`), 而作者以为自己关掉了它。
// 这与"档位拼错静默回落成 chat"是同一类缺陷, 所以要在这里把它拦住。
//
// 判"这个名字存在吗"必须用**静态目录**而不是"实际注册表里有没有它":
//
//	`disallowed-tools: [Bash]` + `tool-profile: analysis`
//	  → analysis 档下 Bash 从来没被注册, 实际黑名单里于是不会有它。
//	    拿实际去判会报"这个名字不存在 (拼错了?)" —— 而它其实是个**正确且冗余**的
//	    声明 (作者在防御性地关掉一个本就不该出现的工具)。
//	  → 静态目录说"Bash 是个真工具", 于是它被正确地接受; 又因为档位下没注册它,
//	    对账那边看到的是"声明要挡, 实际没这个工具" —— 一个零成本的恒真约束, 不是错误。
//
// 所以这两个问题必须由两个不同的判据回答, 不能合并:
//
//	这个名字是不是真工具?   → 本函数 (静态, 只做拼写校验)
//	它到底有没有被挡住?     → collectTools 的实际侧 (Blacklist / Hidden)
//
// ---------------------------------------------------------------------------
// 为什么是"跑一遍注册"而不是一张写死的字符串表
// ---------------------------------------------------------------------------
//
// 写死的表会与 registerProfileTools 的注册语句分家 —— 那正是本仓反复出现的
// "两套真相源"。这里用一个一次性 Registry 跑真实的注册函数, 名字全部来自各工具
// 自己的 Name()。注册是纯内存操作 (构造函数不碰网络/磁盘, searcher 传 nil 即可),
// 且本函数在**装配期**调用一次, 不在热路径上。
//
// 已知的边界: admin 档注册的是"全部内置工具", 而 MCP 动态工具与 CLI 侧另外注册的
// Agent/delegate_task/Skill 等**不在**本目录里 (它们不是 builtin 的一部分, 且随
// 部署而变)。黑名单里出现这类名字会被报成"目录里没有" —— 这是刻意的: 报一个是非
// 判断让人去看一眼, 好过静默放过一个拼错的名字。
//
// ---------------------------------------------------------------------------
// 调用方注意: 判"是不是真工具"应当问 **admin 档**, 而不是"这个资产声明的档"
// ---------------------------------------------------------------------------
//
// 本函数按档位收窄, 但**收窄的语义是"这个档位注册了它", 不是"这个名字合不合法"**。
// 这两个问题在验名时会给出不同的答案, 而错的答案会误报:
//
//	`tool-profile: analysis` + `disallowed-tools: [Bash]`
//	  → 问 analysis 档 ⇒ 目录里没有 Bash ⇒ 报"名字写错了"。
//	  → 但 Bash **是个真工具名**, 只是 analysis 档不注册它。这个声明是作者在
//	    防御性地关掉一个本就不该出现的工具 —— **正确且冗余**。
//
// 所以"是不是真工具"要问 admin 档 (它是各档位的并集, 见 TestAdmin档是各档位的并集),
// "这个档位有没有它"是另一个问题、由别的读数回答 (装配报告的 Hidden / 对账的
// 恒真空约束)。把两者混在一个调用里, 就会得到上面那个误报。
func ToolNameCatalog(profile ToolProfile) []string {
	reg := tool.NewRegistry()
	RegisterProfileToolsWithStore(reg, nil, nil, profile)
	names := reg.Names()
	sort.Strings(names)
	return names
}
