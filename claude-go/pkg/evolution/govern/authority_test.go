// 显式基线优先于默认基线: 运维放宽是一个明确的人为动作。
func TestCheckNoEscalation_显式基线可放宽自动产物(t *testing.T) {
	wide := agent.NewConstraintSet("test:wide").WithToolAllowList([]string{"Read", "Bash"})
	v := CheckNoEscalation(Product{
		Name: "auto-z", AutoGenerated: true, DeclaredTools: []string{"Bash"},
	}, wide)
	// 白名单过了, 但自动产物的 mutating 硬闸仍然挡住 —— 两道一起, 单点放宽不等于提权。
	if v.Allowed {
		t.Fatal("即便基线放宽白名单, 自动产物的写/执行硬闸仍应拦住 Bash")
	}
	if !strings.Contains(strings.Join(v.Reasons, " "), "自动提炼产物不得声明写/执行类工具") {
		t.Errorf("应由 mutating 硬闸拦下, got %v", v.Reasons)
	}
}

