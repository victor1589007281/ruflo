// 基线本身必须是合法约束, 否则 Narrow 会在"父约束不合法"上失败。
func TestDefaultBaseline_自身合法且为只读档(t *testing.T) {
	b := DefaultBaseline()
	if err := b.Validate(); err != nil {
		t.Fatalf("默认基线自身应合法: %v", err)
	}
	if b.ToolProfile() != agent.ProfileAnalysis {
		t.Errorf("默认基线应为 analysis 只读档, got %q", b.ToolProfile())
	}
	if b.Tools == nil || b.Tools.Allow == nil {
		t.Fatal("Allow 必须非 nil 才构成白名单 (nil 是'不设名单', 那就不挡任何东西)")
	}
}
