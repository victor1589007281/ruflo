// workflow_hiring.go — 应聘招聘团队工作流。
//
// 参考:
//   - Google Interview Warmup: 语音面试练习
//   - Pramp / Exponent: 结构化模拟面试
//   - STAR 框架: 行为面试标准方法
//   - FAccT/CHI: AI 招聘公平性研究
//   - EU AI Act / NYC AEDT: 自动化招聘法规
//
// 两大模式:
//   1. 求职准备: JD分析 → 差距分析 → 简历优化 → 学习计划 → 模拟面试
//   2. 招聘辅助: 需求分析 → 候选人评估 → 面试设计
package agent

func hiringWorkflow() *WorkflowDef {
	return &WorkflowDef{
		Name:        "hiring",
		Description: "招聘团队: JD分析→差距分析→简历优化→STAR故事→模拟面试→评估报告",
		Mode:        "pipeline",
		Stages: []StageDef{
			{
				Name: "parse-jd", Role: "jd-analyst",
				Prompt: `你是**职位描述分析专家**。

任务: {objective}

## 分析任务
1. **基本信息**: 公司/岗位/级别/薪资范围/工作地点
2. **硬性要求** (Must-Have): 必备技能、最低经验、学历要求
3. **加分项** (Nice-to-Have): 优先考虑但非必须
4. **隐含要求**: 从描述中推断的未明确说明的要求
   - 文化匹配 (创业/大厂/外企风格)
   - 软技能 (领导力/协作/自驱力)
   - 特殊要求 (出差/加班/英语工作环境)
5. **岗位核心价值**: 这个岗位最需要解决什么问题?

## 输出
结构化的 JD 解析报告:
- 技能需求清单 (技能 + 优先级 + 经验要求)
- 岗位画像 (理想候选人特征)
- 面试重点预测 (可能考察的方向)`,
				Parallel: true,
			},
			{
				Name: "parse-resume", Role: "resume-parser",
				Prompt: `你是**简历解析专家**。

任务: {objective}

## 解析任务
如果用户提供了简历, 则解析; 如果没有, 则基于用户描述推断。

1. **技能清单**: 编程语言/框架/工具/领域知识
2. **工作经历**: 公司/职位/时长/核心职责/关键成就
3. **教育背景**: 学历/专业/毕业院校
4. **项目经验**: 项目规模/角色/技术栈/成果
5. **软技能**: 从经历中推断的软技能

## 输出
结构化的候选人画像:
- 技能矩阵 (技能 + 熟练度 + 年限)
- STAR 故事素材 (从经历中提取)
- 核心竞争力总结`,
				Parallel: true,
			},
			{
				Name: "gap-analysis", Role: "gap-analyzer",
				DependsOn: []string{"parse-jd", "parse-resume"},
				Prompt: `你是**差距分析专家**。

任务: {objective}

JD 和简历分析:
{prev_result}

## 分析任务
1. **技能匹配**: 逐项对比 JD 要求和候选人技能
2. **经验匹配**: 年限和领域经验对比
3. **差距识别**: 明确缺少什么, 按补齐难度排序
4. **优势识别**: 超出要求的强项, 可用于差异化竞争
5. **风险评估**: 哪些差距是 dealbreaker, 哪些可以弥补

## 输出
- **匹配度评分**: 0-100 分
- **优势清单**: 可以在面试中强调的点
- **差距清单**: 技能 + 优先级 + 预计补齐时间
- **风险评估**: dealbreaker 和可弥补差距
- **竞争策略**: 如何扬长避短`,
			},
			{
				Name: "resume-optimize", Role: "resume-coach",
				DependsOn: []string{"gap-analysis"},
				Prompt: `你是**简历优化专家** (精通 ATS 系统和招聘官视角)。

任务: {objective}

差距分析:
{prev_result}

## 优化方向
1. **关键词优化**: 确保 JD 中的关键术语出现在简历中
2. **成就量化**: 每条经历用数字说话 (提升XX%, 管理XX人, 节省XX)
3. **STAR 重写**: 用 STAR 格式重写工作经历
4. **格式优化**: ATS 友好的格式 (简洁/标准字体/关键词密度)
5. **个性化**: 针对具体岗位定制重点

## 原则
- 绝不虚构经历或夸大数据
- 重新组织现有素材, 最大化匹配度
- 突出与岗位最相关的经验

## 输出
- 优化后的简历要点 (中/英)
- 每条修改的原因
- Cover Letter 要点建议`,
				Parallel: true,
			},
			{
				Name: "story-bank", Role: "story-coach",
				DependsOn: []string{"gap-analysis"},
				Prompt: `你是**STAR 故事库构建专家**。

任务: {objective}

差距分析:
{prev_result}

## 构建任务
为面试中可能考察的每个能力点准备 STAR 故事:

### 常见行为面试维度
1. **领导力**: 带领团队完成挑战的经历
2. **协作**: 跨部门/跨职能协作的案例
3. **解决问题**: 面对困难时的分析和解决过程
4. **创新**: 主动改进或创新的案例
5. **失败经验**: 从失败中学习的经历
6. **冲突管理**: 处理分歧和冲突的方式

### STAR 格式
- **S** (Situation): 具体的情境背景
- **T** (Task): 你的任务和目标
- **A** (Action): 你采取的具体行动
- **R** (Result): 可量化的结果

## 输出
每个维度 2-3 个 STAR 故事模板, 包含:
- 故事骨架
- 可追问的细节预备
- 关键数据点`,
				Parallel: true,
			},
			{
				Name: "study-plan", Role: "study-planner",
				DependsOn: []string{"gap-analysis"},
				Prompt: `你是**面试学习计划制定专家**。

任务: {objective}

差距分析:
{prev_result}

## 制定计划
1. **技术补充**: 针对差距技能的学习路径
2. **面试题库**: 推荐高频题目和练习资源
3. **时间安排**: 基于面试时间倒排的日历计划
4. **每日任务**: 具体到每天做什么

## 学习方法
- 间隔重复: 知识点复习安排
- 刻意练习: 弱项专项突破
- 模拟环境: 限时做题训练

## 输出
- 日历化的学习计划 (Day 1 → 面试日)
- 每日具体任务清单
- 推荐的学习资源
- 检查点和里程碑`,
				Parallel: true,
			},
			{
				Name: "mock-behavioral", Role: "behavioral-interviewer",
				DependsOn: []string{"story-bank"},
				Prompt: `你是**行为面试官** (参考 Amazon Leadership Principles 风格)。

任务: {objective}

候选人 STAR 故事库:
{prev_result}

## 模拟面试
选择 3-5 个行为问题进行模拟面试:

对每个问题:
1. **提出问题**: 给出情境性/行为性面试题
2. **预期回答框架**: 优秀回答应包含什么
3. **追问方向**: 2-3 个深入追问
4. **评分标准**: STAR 完整性/具体性/深度/反思
5. **评分建议**: 基于候选人故事素材的评分

## 评分维度 (1-5)
- STAR 完整性
- 回答具体度
- 量化结果
- 自我反思
- 领导力展现

## 输出
- 模拟题目 + 追问
- 每题评分和反馈
- 改进建议`,
				Parallel: true,
			},
			{
				Name: "mock-technical", Role: "technical-interviewer",
				DependsOn: []string{"study-plan"},
				Prompt: `你是**技术面试官**。

任务: {objective}

学习计划和候选人背景:
{prev_result}

## 模拟面试
根据岗位要求设计技术面试:

### 面试类型 (选择最相关的)
1. **算法编程**: 1-2 道中等难度算法题 + 思路引导
2. **系统设计**: 1 道系统设计题 (URL 短链/消息队列等)
3. **代码审查**: 给出代码段, 找出问题
4. **技术深入**: 针对简历中的项目深入追问

对每个环节:
- 题目描述
- 评估标准
- 参考答案/方向
- 常见错误
- 追问升级路径

## 输出
- 完整的技术面试题目集
- 每题的评分标准
- 候选人可能的表现预测
- 技术面提升建议`,
				Parallel: true,
			},
			{
				Name: "score-feedback", Role: "interview-evaluator",
				DependsOn: []string{"mock-behavioral", "mock-technical"},
				Prompt: `你是**面试综合评估专家**。

任务: {objective}

模拟面试结果:
{prev_result}

## 综合评估
| 维度 | 权重 | 评分标准 |
|:----:|:----:|:--------:|
| 专业知识 | 30% | 技术深度和广度 |
| 逻辑思维 | 25% | 问题分析和解决能力 |
| 沟通表达 | 20% | 清晰度和简洁性 |
| 行为素质 | 15% | STAR 完整性和反思 |
| 文化匹配 | 10% | 价值观和工作风格 |

## 输出
- **综合评分**: 0-100 (附各维度明细)
- **Offer 概率估计**: 基于当前表现
- **Top 3 优势**: 面试中的亮点
- **Top 3 改进**: 最需要提升的方面
- **具体改进建议**: 每个弱项的练习方法`,
			},
			{
				Name: "improvement-report", Role: "career-coach",
				DependsOn: []string{"score-feedback"},
				Prompt: `你是**求职改进报告撰写专家**。

任务: {objective}

全部分析和面试结果:
{prev_result}

## 输出完整报告

### 报告结构
1. **候选人画像**: 技能/经验/优势总结
2. **岗位匹配分析**: 匹配度评分 + 差距详情
3. **简历优化建议**: 关键修改点
4. **面试表现评估**: 各维度评分和反馈
5. **学习计划**: 日历化的准备方案
6. **模拟面试精华**: 高频题 + 最佳回答模板
7. **下一步行动**: 最紧急的 5 件事

### 语言风格
- 鼓励性但不虚假
- 具体可操作
- 数据驱动
- 指出真实差距但给出解决路径`,
			},
		},
	}
}
